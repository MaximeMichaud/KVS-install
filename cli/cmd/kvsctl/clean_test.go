func TestDirSize(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a"), make([]byte, 100), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "sub"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "sub", "b"), make([]byte, 50), 0o600); err != nil {
		t.Fatal(err)
	}
	if size := dirSize(dir); size != 150 {
		t.Fatalf("size is %d, wanted 150", size)
	}
}

func TestImageCandidates(t *testing.T) {
	cases := map[string]string{
		"ghcr.io/x/php:0.3.0@sha256:abc":                    "ghcr.io/x/php:0.3.0 ghcr.io/x/php@sha256:abc",
		"127.0.0.1:5000/kvs-install/nginx:0.2.0@sha256:f3d": "127.0.0.1:5000/kvs-install/nginx:0.2.0 127.0.0.1:5000/kvs-install/nginx@sha256:f3d",
		"ghcr.io/x/php@sha256:abc":                          "ghcr.io/x/php@sha256:abc",
		"ghcr.io/x/php:0.3.0":                               "ghcr.io/x/php:0.3.0",
		"${KVS_PHP_FPM_IMAGE}":                              "",
	}
	for ref, want := range cases {
		if got := strings.Join(imageCandidates(ref), " "); got != want {
			t.Errorf("imageCandidates(%q) = %q, want %q", ref, got, want)
		}
	}
}

// The pins recorded by an upgrade name the variant images, which the
// override only reads from .env, and a pin shared with a kept version stays
// under every form the engine lists it by.
func TestCleanTargetsUsesTheRecordedPins(t *testing.T) {
	stateDir := t.TempDir()
	state := &instance.State{
		Current:  "0.2.0",
		Previous: "0.1.0",
		ReleaseImages: map[string][]string{
			"0.2.0": {"r/nginx:0.2.0@sha256:n2", "r/php:0.2.0@sha256:p2"},
			"0.3.0": {"r/nginx:0.2.0@sha256:n2", "r/php:0.3.0@sha256:p3"},
		},
	}
	plan, err := cleanTargets(stateDir, state)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(plan.Images, " "); got != "r/php:0.3.0 r/php@sha256:p3" {
		t.Fatalf("images to remove are %q", got)
	}
	if strings.Join(plan.Dropped, " ") != "0.3.0" {
		t.Fatalf("dropped versions are %v", plan.Dropped)
	}
	local := []string{"r/php:0.3.0", "r/nginx:0.2.0", "r/php:0.2.0"}
	if got := strings.Join(onlyLocal(plan.Images, local), " "); got != "r/php:0.3.0" {
		t.Fatalf("the engine holds %q of those", got)
	}
}
