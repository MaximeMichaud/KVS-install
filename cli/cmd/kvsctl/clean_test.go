func writeOverride(t *testing.T, stateDir, version string, images map[string]string) {
	t.Helper()
	dir := filepath.Join(stateDir, "releases", version, "docker")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	body := "# Generated by kvsctl-release for stack " + version + "\nservices:\n"
	for _, service := range []string{"nginx", "php-fpm"} {
		if ref, ok := images[service]; ok {
			body += "  " + service + ":\n    image: \"" + ref + "\"\n"
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "docker-compose.release.yml"), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestRefsFromOverride(t *testing.T) {
	stateDir := t.TempDir()
	writeOverride(t, stateDir, "0.2.0", map[string]string{"nginx": "ghcr.io/x/nginx:0.2.0", "php-fpm": "ghcr.io/x/php:0.2.0"})
	refs, err := refsFromOverride(filepath.Join(stateDir, "releases", "0.2.0", "docker", "docker-compose.release.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(refs, " ") != "ghcr.io/x/nginx:0.2.0 ghcr.io/x/php:0.2.0" {
		t.Fatalf("refs are %v", refs)
	}
	missing, err := refsFromOverride(filepath.Join(stateDir, "releases", "9.9.9", "docker", "docker-compose.release.yml"))
	if err != nil || missing != nil {
		t.Fatalf("a missing override gave %v, %v", missing, err)
	}
}

// TestCleanTargets checks the two rules that matter: the current and the
// previous version stay, and an image several versions share is kept as
// long as one of those two pins it.
func TestCleanTargets(t *testing.T) {
	stateDir := t.TempDir()
	writeOverride(t, stateDir, "0.1.0", map[string]string{"nginx": "ghcr.io/x/nginx:0.1.0", "php-fpm": "ghcr.io/x/php:0.1.0"})
	writeOverride(t, stateDir, "0.2.0", map[string]string{"nginx": "ghcr.io/x/nginx:shared", "php-fpm": "ghcr.io/x/php:0.2.0"})
	writeOverride(t, stateDir, "0.3.0", map[string]string{"nginx": "ghcr.io/x/nginx:shared", "php-fpm": "ghcr.io/x/php:0.3.0"})
	// 0.0.9 is only in the history: its files are already gone, and so is
	// anything kvsctl could have known about its images.
	downloads := filepath.Join(stateDir, "downloads")
	if err := os.MkdirAll(downloads, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(downloads, "kvs-stack-0.3.0.tar.gz"), []byte("bundle"), 0o600); err != nil {
		t.Fatal(err)
	}
	state := &instance.State{
		Current:  "0.3.0",
		Previous: "0.2.0",
		History: []instance.Entry{
			{Version: "0.0.9", Action: "adopt"},
			{Version: "0.1.0", Action: "upgrade"},
		},
	}
	plan, err := cleanTargets(stateDir, state)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(plan.Images, " "); got != "ghcr.io/x/nginx:0.1.0 ghcr.io/x/php:0.1.0" {
		t.Fatalf("images to remove are %q", got)
	}
	if len(plan.Releases) != 1 || filepath.Base(plan.Releases[0]) != "0.1.0" {
		t.Fatalf("release directories are %v", plan.Releases)
	}
	if plan.Downloads != downloads {
		t.Fatalf("downloads are %q", plan.Downloads)
	}
	if strings.Join(plan.Kept, " ") != "0.2.0 0.3.0" {
		t.Fatalf("kept versions are %v", plan.Kept)
	}
	if summary := cleanSummary(plan); summary != "2 images, 1 kept release, the downloaded bundles" {
		t.Fatalf("summary is %q", summary)
	}
}

// TestCleanTargetsWithoutState keeps every version: nothing says which
// images a rollback still needs.
func TestCleanTargetsWithoutState(t *testing.T) {
	stateDir := t.TempDir()
	writeOverride(t, stateDir, "0.1.0", map[string]string{"nginx": "ghcr.io/x/nginx:0.1.0"})
	downloads := filepath.Join(stateDir, "downloads")
	if err := os.MkdirAll(downloads, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(downloads, "bundle.tar.gz"), []byte("x"), 0o600); err != nil {
		t.Fatal(err)
	}
	plan, err := cleanTargets(stateDir, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Images) != 0 || len(plan.Releases) != 0 {
		t.Fatalf("an unadopted stack would lose %v and %v", plan.Images, plan.Releases)
	}
	if plan.Downloads != downloads {
		t.Fatalf("downloads are %q", plan.Downloads)
	}
}

